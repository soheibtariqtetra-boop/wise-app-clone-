/** Newest calendar date first; preserve PDF source order within the same day. */
export function sortStatementTransactions(transactions) {
  return [...transactions].sort((a, b) => {
    const byDate = Date.parse(b.dateStr) - Date.parse(a.dateStr)
    if (byDate !== 0) return byDate
    return (a.sourceOrder ?? 0) - (b.sourceOrder ?? 0)
  })
}

