/**
 * Build an unofficial demo transfer-confirmation PDF from verified
 * fields on the current transaction record only.
 * @param {object} transaction
 * @returns {Promise<{ blob: Blob, filename: string }>}
 */
export async function generateTransferConfirmationPdf(transaction) {
  if (!transaction) {
    throw new Error('No transaction available')
  }

  const { jsPDF } = await import('jspdf')

  const amount = String(transaction.amount || '')
    .replace(/^-/, '')
    .trim()
  const currency = transaction.currency || 'EUR'
  const amountLabel = amount.includes(currency)
    ? amount
    : `${amount} ${currency}`.trim()

  const recipient =
    transaction.fullRecipientName
    || transaction.title
    || transaction.displayName
    || '—'

  const bank = transaction.recipientBankDetails || null
  const lines = [
    ['Document type', 'Unofficial demo transfer confirmation'],
    ['Clone notice', 'Not an official Wise receipt or proof of payment'],
    ['Recipient', recipient],
    ['You sent', amountLabel || '—'],
    ["Wise's fees", `0 ${currency}`],
    [
      'Recipient received',
      transaction.recipientReceivedLabel
        ? `${transaction.recipientReceivedLabel}: ${amountLabel}`
        : amountLabel || '—',
    ],
    ['Transaction number', transaction.transactionNumber || '—'],
    ['Date', transaction.date || transaction.dateGroup || '—'],
  ]

  if (bank) {
    lines.push(
      ['Account holder name', bank.accountHolderName || '—'],
      ['Bank code (BIC/SWIFT)', bank.swiftBic || '—'],
      ['IBAN', bank.iban || '—'],
      [
        'Bank name',
        Array.isArray(bank.bankNameLines) && bank.bankNameLines.length
          ? bank.bankNameLines.join(' ')
          : '—',
      ],
    )
  }

  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const marginX = 48
  let y = 56

  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  doc.text('Transfer confirmation (demo)', marginX, y)
  y += 22

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  doc.setTextColor(80)
  const disclaimer = doc.splitTextToSize(
    'This document was generated by the Wise Business Clone for demonstration only. '
    + 'It is not issued by Wise and must not be used as an official payment confirmation.',
    500,
  )
  doc.text(disclaimer, marginX, y)
  y += disclaimer.length * 14 + 18
  doc.setTextColor(0)

  doc.setFontSize(11)
  for (const [label, value] of lines) {
    doc.setFont('helvetica', 'bold')
    doc.text(`${label}`, marginX, y)
    doc.setFont('helvetica', 'normal')
    const wrapped = doc.splitTextToSize(String(value), 320)
    doc.text(wrapped, marginX + 160, y)
    y += Math.max(18, wrapped.length * 14)
    if (y > 760) {
      doc.addPage()
      y = 56
    }
  }

  const safeId = String(transaction.id || 'transfer')
    .replace(/[^a-zA-Z0-9-_]/g, '-')
  const filename = `transfer-confirmation-${safeId}.pdf`
  const blob = doc.output('blob')

  return { blob, filename }
}

/**
 * Trigger a browser download for the given blob.
 */
export function triggerBlobDownload(blob, filename) {
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = filename
  anchor.rel = 'noopener'
  document.body.appendChild(anchor)
  anchor.click()
  anchor.remove()
  return url
}
